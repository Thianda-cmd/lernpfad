export function formelProblem(f: FormelTask): Problem {
  return {
    prompt: `Stelle die Formel nach $${f.targetTex}$ um. (${f.context})`,
    tex: f.formula,
    answer: { kind: 'expr', value: f.answer, vars: f.vars, label: `${f.targetTex.replace(/_(\w+)/, '_$1')} =` },
    steps: f.steps,
    hint: 'Zwiebelprinzip: die Rechenschritte um die gesuchte Größe von außen nach innen mit der Umkehroperation rückgängig machen.',
  }
}

export const FORMEL_GENS: GenInfo[] = [
  {
    id: 'umstellen',
    title: 'Formeln umstellen',
    gen: (rng, level) => {
      const pool = FORMELN.filter((f) => f.level === level)
      return formelProblem(pick(rng, pool.length ? pool : FORMELN))
    },
  },
]
